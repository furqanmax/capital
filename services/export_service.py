# Writers
# --------------------------------------------------------------------------


def _write_csv(request: ExportRequest, path: Path) -> None:
    with open(path, "w", newline="", encoding="utf-8-sig") as handle:
        writer = csv.writer(handle)
        for row in provenance_rows(request):
            writer.writerow(row)
        writer.writerow([])
        writer.writerow(column_labels(request.frame))
        for record in display_frame(request.frame).itertuples(index=False):
            writer.writerow(["" if _is_na(v) else v for v in record])


def _write_excel(request: ExportRequest, path: Path) -> None:
    import xlsxwriter

    frame = display_frame(request.frame)
    labels = column_labels(frame)

    workbook = xlsxwriter.Workbook(str(path), {"nan_inf_to_errors": True})
    header_fmt = workbook.add_format({
        "bold": True, "bg_color": "#1F3B57", "font_color": "white",
        "border": 1, "text_wrap": True, "valign": "vcenter",
    })
    title_fmt = workbook.add_format({"bold": True, "font_size": 14})
    label_fmt = workbook.add_format({"bold": True, "bg_color": "#EEF2F6", "border": 1})
    value_fmt = workbook.add_format({"border": 1})
    number_fmt = workbook.add_format({"num_format": "#,##0.00", "border": 1})
    integer_fmt = workbook.add_format({"num_format": "#,##0", "border": 1})
    date_fmt = workbook.add_format({"num_format": "yyyy-mm-dd", "border": 1})

    # ---- provenance sheet -------------------------------------------
    meta = workbook.add_worksheet("Report Info")
    meta.set_column(0, 0, 26)
    meta.set_column(1, 1, 90)
    meta.write(0, 0, request.title, title_fmt)
    provenance = provenance_frame(request)
    for row_idx, (key, value) in enumerate(provenance.itertuples(index=False), start=2):
        meta.write(row_idx, 0, str(key), label_fmt)
        meta.write(row_idx, 1, "" if value is None else str(value), value_fmt)

    # ---- data sheet ---------------------------------------------------
    sheet = workbook.add_worksheet(_safe_sheet_name(request.title))
    for col_idx, label in enumerate(labels):
        sheet.write(0, col_idx, label, header_fmt)
    sheet.freeze_panes(1, 0)
    sheet.autofilter(0, 0, max(1, len(frame)), max(0, len(labels) - 1))

    for col_idx, column in enumerate(frame.columns):
        series = frame[column]
        width = max(10, min(28, max([len(str(labels[col_idx]))] +
                                    [len(str(v)) for v in series.head(200)]) + 2))
        sheet.set_column(col_idx, col_idx, width)

        if pd.api.types.is_integer_dtype(series) or column in ("tottrdqty", "totaltrades"):
            fmt = integer_fmt
        elif column in ("trade_date",):
            fmt = date_fmt
        elif pd.api.types.is_numeric_dtype(series):
            fmt = number_fmt
        else:
            fmt = value_fmt

        for row_idx, value in enumerate(series.tolist(), start=1):
            if _is_na(value):
                sheet.write_blank(row_idx, col_idx, None, fmt)
            elif column == "trade_date":
                sheet.write_datetime(row_idx, col_idx, _as_datetime(value), fmt)
            else:
                sheet.write(row_idx, col_idx, value, fmt)

    # ---- any extra sheets ---------------------------------------------
    for name, extra in request.extra_sheets.items():
        extra_sheet = workbook.add_worksheet(_safe_sheet_name(name))
        extra_frame = display_frame(extra)
        for col_idx, column in enumerate(extra_frame.columns):
            extra_sheet.write(0, col_idx, column.replace("_", " ").title(), header_fmt)
            extra_sheet.set_column(col_idx, col_idx, 18)
        for row_idx, record in enumerate(extra_frame.itertuples(index=False), start=1):
            for col_idx, value in enumerate(record):
                if _is_na(value):
                    extra_sheet.write_blank(row_idx, col_idx, None, value_fmt)
                else:
                    extra_sheet.write(row_idx, col_idx, value, value_fmt)

    workbook.close()


def _write_pdf(request: ExportRequest, path: Path) -> None:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    frame = display_frame(request.frame)
    labels = column_labels(frame)

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("CapitalTitle", parent=styles["Title"], fontSize=16,
                                 spaceAfter=6)
    note_style = ParagraphStyle("CapitalNote", parent=styles["Normal"], fontSize=8,
                                textColor=colors.HexColor("#444444"))

    doc = SimpleDocTemplate(
        str(path), pagesize=landscape(A4),
        leftMargin=12 * mm, rightMargin=12 * mm, topMargin=12 * mm, bottomMargin=12 * mm,
        title=request.title, author=request.generated_by,
    )
    story: List[Any] = [Paragraph(request.title, title_style), Spacer(1, 4 * mm)]

    meta_table = Table(
        [[str(k), str(v)] for k, v in provenance_frame(request).itertuples(index=False)],
        colWidths=[45 * mm, 200 * mm],
    )
    meta_table.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
        ("TOPPADDING", (0, 0), (-1, -1), 2),
        ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#CCCCCC")),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#EEF2F6")),
    ]))
    story.append(meta_table)
    story.append(Spacer(1, 6 * mm))
    story.append(Paragraph(
        "Columns marked with * are calculated metrics; all other columns are imported data.",
        note_style,
    ))
    story.append(Spacer(1, 4 * mm))

    max_rows = 4000
    subset = frame.head(max_rows)
    data: List[List[str]] = [labels]
    for record in subset.itertuples(index=False):
        data.append([_pdf_cell(value) for value in record])

    table = Table(data, repeatRows=1)
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1F3B57")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 6),
        ("GRID", (0, 0), (-1, -1), 0.2, colors.HexColor("#BBBBBB")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F5F7F9")]),
        ("ALIGN", (0, 0), (-1, -1), "LEFT"),
    ]))
    story.append(table)
    if len(frame) > max_rows:
        story.append(Spacer(1, 3 * mm))
        story.append(Paragraph(
            f"Showing the first {max_rows:,} of {len(frame):,} rows. "
            "Use the Excel or CSV export for the complete dataset.", note_style))

    doc.build(story)


# --------------------------------------------------------------------------
# helpers
# --------------------------------------------------------------------------


def _is_na(value: Any) -> bool:
    try:
        return bool(pd.isna(value))
    except (TypeError, ValueError):
        return False


def _as_datetime(value: Any) -> _dt.datetime:
    if isinstance(value, _dt.datetime):
        return value
    if isinstance(value, _dt.date):
        return _dt.datetime(value.year, value.month, value.day)
    return pd.to_datetime(value).to_pydatetime()


def _pdf_cell(value: Any) -> str:
    if _is_na(value):
        return ""
    if isinstance(value, float):
        return round_display(value, 2)
    return str(value)


def _safe_sheet_name(name: str) -> str:
    cleaned = "".join(ch for ch in str(name) if ch not in "[]:*?/\\")
    return (cleaned or "Data")[:31]


def default_export_path(title: str, fmt: str = "xlsx") -> Path:
    stamp = _dt.datetime.now().strftime("%Y%m%d-%H%M%S")
    slug = "".join(ch if ch.isalnum() else "-" for ch in title.lower()).strip("-") or "report"
    return PROJECT_ROOT / "data" / "exports" / f"{slug}-{stamp}.{fmt}"


