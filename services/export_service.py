"""Report and export service — Excel, CSV and PDF.

Every export carries the same provenance block:

* the exact date/time the report was generated,
* the filters and duplicate policy that were active,
* which columns are *calculated* (engine- or formula-derived) versus imported.

That is what makes an exported file auditable: a calculated metric is always
labelled as such and never presented as source data.
"""

from __future__ import annotations

import csv
import datetime as _dt
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Mapping

import pandas as pd

from database.db import PROJECT_ROOT, resolve_path

from .formatting import round_display

#: Columns that come straight from the imported worksheet.
RAW_COLUMNS = (
    "symbol", "trade_date", "open", "high", "low", "close", "last", "prevclose",
    "tottrdqty", "tottrdval", "totaltrades", "delivery_pct",
)

#: Columns produced by the analytics engine (never imported).
CALCULATED_COLUMNS = (
    "deliverable_qty", "avg_price", "pct_change", "action", "vol_ma", "vol_level",
    "v1", "vol_badge", "trade_indicator", "cmp", "avg_price_avg", "delivery_avg",
    "action_avg", "cmp_verdict", "today_delivery", "avg_delivery", "today_volume",
    "avg_volume", "today_trades", "avg_trades", "d_ind", "dv1", "dv2",
)

EXPORT_FORMATS = ("xlsx", "csv", "pdf")


@dataclass
class ExportRequest:
    title: str
    frame: pd.DataFrame
    path: str | Path
    format: str = "xlsx"
    filters: Mapping[str, Any] = field(default_factory=dict)
    notes: str = ""
    generated_by: str = "Capital"
    extra_sheets: Dict[str, pd.DataFrame] = field(default_factory=dict)

    def resolved_path(self) -> Path:
        path = resolve_path(self.path)
        path.parent.mkdir(parents=True, exist_ok=True)
        return path


@dataclass
class ExportResult:
    path: Path
    format: str
    rows: int
    columns: int
    generated_at: _dt.datetime

    def summary(self) -> Dict[str, Any]:
        return {
            "path": str(self.path),
            "format": self.format,
            "rows": self.rows,
            "columns": self.columns,
            "generated_at": self.generated_at.isoformat(timespec="seconds"),
        }


def export(request: ExportRequest) -> ExportResult:
    fmt = request.format.lower().lstrip(".")
    if fmt not in EXPORT_FORMATS:
        raise ValueError(f"unsupported export format {request.format!r}; "
                         f"expected one of {', '.join(EXPORT_FORMATS)}")
    path = request.resolved_path()
    if fmt == "csv":
        _write_csv(request, path)
    elif fmt == "xlsx":
        _write_excel(request, path)
    else:
        _write_pdf(request, path)
    return ExportResult(path=path, format=fmt, rows=len(request.frame),
                        columns=len(request.frame.columns), generated_at=_dt.datetime.now())


# --------------------------------------------------------------------------
# Column labelling
# --------------------------------------------------------------------------


def display_frame(frame: pd.DataFrame) -> pd.DataFrame:
    """Return a copy with human-friendly headers and formatted dates."""
    out = frame.copy()
    for column in out.columns:
        if pd.api.types.is_datetime64_any_dtype(out[column]):
            out[column] = pd.to_datetime(out[column]).dt.date
    return out


def column_labels(frame: pd.DataFrame) -> List[str]:
    from .analytics import COLUMN_LABELS

    labels: List[str] = []
    for column in frame.columns:
        label = COLUMN_LABELS.get(column, column.replace("_", " ").title())
        if column in CALCULATED_COLUMNS:
            label = f"{label} *"
        labels.append(label)
    return labels


def provenance_rows(request: ExportRequest) -> List[List[Any]]:
    generated = _dt.datetime.now()
    rows: List[List[Any]] = [
        ["Report", request.title],
        ["Generated at", generated.strftime("%Y-%m-%d %H:%M:%S")],
        ["Generated by", request.generated_by],
        ["Rows", len(request.frame)],
        ["Columns", len(request.frame.columns)],
        ["Formula mode", request.filters.get("formula_mode", "original")],
    ]
    for key, value in request.filters.items():
        rows.append([f"Filter: {key}", value])
    calculated = [c for c in request.frame.columns if c in CALCULATED_COLUMNS]
    rows.append(["Calculated columns", ", ".join(calculated) if calculated else "(none)"])
    rows.append(["Note", "Columns marked with * are calculated by the analytics engine "
                         "or a Formula Lab expression; every other column is imported "
                         "source data."])
    if request.notes:
        rows.append(["Notes", request.notes])
    return rows


def provenance_frame(request: ExportRequest) -> pd.DataFrame:
    return pd.DataFrame(provenance_rows(request), columns=["Field", "Value"])


